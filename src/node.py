"""
Neural node representation for the DenSOINN network.
"""
import numpy as np


class Node:
    """
    A single neural node in the DenSOINN network (Section 3.2 of the paper).

    Each node is the prototype of a micro-cluster: it stores the centroid
    (feature vector w_i) of the input patterns mapped to it, together with
    an accumulated weight m_i (the effective count of absorbed patterns).
    The activation threshold t_i is NOT stored here, it is derived from the
    node's topological neighbors in the network (see DenSOINNNetwork).
    """

    def __init__(self, node_id: int, w: np.ndarray):
        self.id = node_id      # unique node id (generated by the network)
        self.w = w             # centroid / feature vector w_i
        self.m = 1.0           # accumulated pattern count (node weight m_i)

    def absorb(self, x: np.ndarray) -> None:
        """
        Pull the centroid toward x and increase the count (Eq. 7).

        The count is incremented first so the new m_i is the denominator of the
        learning rate; this makes w_i the running mean of all absorbed patterns.
        """
        self.m += 1.0
        self.w = self.w + (1.0 / self.m) * (x - self.w)
